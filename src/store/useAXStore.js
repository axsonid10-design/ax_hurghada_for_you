export const useAXStore = create((set) => ({
  profile: {
    id: 'user_admin',
    name: 'مدير التشغيل',
    role: 'Operations Director'
  },
  isAuthLoading: false,
  realtimeTrigger: 0,
  isOnline: typeof navigator !== 'undefined' ? navigator.onLine : true,
  activeTab: 'daily',
  sidebarPinned: true,
  sidebarCollapsed: false,
  selectedDate: '2026-10-24',
  pendingSyncCount: 0,
  bookings: INITIAL_BOOKINGS,
  searchQuery: '',

  confirmModal: {
    isOpen: false,
    title: '',
    message: '',
    confirmText: 'تأكيد',
    cancelText: 'إلغاء',
    type: 'danger',
    onConfirm: () => {}
  },

  setActiveTab: (tab) => set({ activeTab: tab }),
  toggleSidebarPin: () => set((state) => ({ sidebarPinned: !state.sidebarPinned })),
  toggleSidebarCollapse: () => set((state) => ({ sidebarCollapsed: !state.sidebarCollapsed })),
  setSelectedDate: (date) => set({ selectedDate: date }),
  setSearchQuery: (query) => set({ searchQuery: query }),
  setPendingSyncCount: (count) => set({ pendingSyncCount: count }),
  setIsOnline: (online) => set({ isOnline: online }),

  openConfirmModal: ({ title, message, confirmText, cancelText, type, onConfirm }) => set({
    confirmModal: {
      isOpen: true,
      title,
      message,
      confirmText: confirmText || 'تأكيد',
      cancelText: cancelText || 'إلغاء',
      type: type || 'danger',
      onConfirm
    }
  }),

  closeConfirmModal: () => set({
    confirmModal: {
      isOpen: false,
      title: '',
      message: '',
      confirmText: 'تأكيد',
      cancelText: 'إلغاء',
      type: 'danger',
      onConfirm: () => {}
    }
  }),

  addBooking: (booking) => set((state) => ({
    bookings: [booking, ...state.bookings]
  })),

  updateBooking: (sr, updatedFields) => set((state) => ({
    bookings: state.bookings.map((b) => (b.sr === sr ? { ...b, ...updatedFields } : b))
  })),

  deleteBooking: (sr) => set((state) => ({
    bookings: state.bookings.filter((b) => b.sr !== sr)
  }))
}))
